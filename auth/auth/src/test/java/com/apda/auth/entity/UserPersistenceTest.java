package com.apda.auth.entity;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.Statement;
import java.util.UUID;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.springframework.boot.data.jpa.test.autoconfigure.DataJpaTest;
import org.springframework.boot.jdbc.test.autoconfigure.AutoConfigureTestDatabase;
import org.springframework.core.io.ClassPathResource;
import org.springframework.jdbc.datasource.init.ScriptUtils;

import com.apda.auth.repository.UserRepository;

import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.TestConfiguration;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Import;
import org.springframework.security.crypto.bcrypt.BCryptPasswordEncoder;
import org.springframework.security.crypto.password.PasswordEncoder;

@DataJpaTest(properties = {
        "spring.datasource.url=jdbc:h2:mem:auth-persistence-test;DB_CLOSE_DELAY=-1",
        "spring.datasource.username=sa",
        "spring.datasource.password=",
        "spring.jpa.hibernate.ddl-auto=validate",
        "spring.sql.init.mode=always"
})
@AutoConfigureTestDatabase(replace = AutoConfigureTestDatabase.Replace.NONE)
@Import(UserPersistenceTest.EncoderConfig.class)
class UserPersistenceTest {

    // Slice @DataJpaTest tidak memuat SecurityConfig, sedangkan CommandLineRunner
    // seedAdminUser butuh PasswordEncoder; sediakan encoder di slice tes ini.
    @TestConfiguration
    static class EncoderConfig {
        @Bean
        PasswordEncoder passwordEncoder() {
            return new BCryptPasswordEncoder();
        }
    }

    @Autowired
    private UserRepository userRepository;

    @Test
    void persistsEmailAndAllowsLegacyRowsWithoutEmail() {
        User legacyUser = new User("existing-user", "existing-hash", "PELANGGAN");
        userRepository.saveAndFlush(legacyUser);
        assertNull(userRepository.findByUsername("existing-user").orElseThrow().getEmail());

        User newUser = new User("new-user", "new-hash", "PELANGGAN");
        newUser.setEmail("new-user@example.test");
        userRepository.saveAndFlush(newUser);

        assertEquals("new-user@example.test",
                userRepository.findByUsername("new-user").orElseThrow().getEmail());
    }

    @Test
    void appliesEmailMigrationIdempotentlyAndPreservesExistingColumns() throws Exception {
        String databaseName = "auth_migration_" + UUID.randomUUID().toString().replace("-", "");
        String jdbcUrl = "jdbc:h2:mem:" + databaseName + ";DB_CLOSE_DELAY=-1";

        try (Connection connection = DriverManager.getConnection(jdbcUrl, "sa", "");
             Statement statement = connection.createStatement()) {
            statement.execute("""
                    CREATE TABLE users (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        username VARCHAR(255) NOT NULL UNIQUE,
                        password VARCHAR(255) NOT NULL,
                        role VARCHAR(255) NOT NULL
                    )
                    """);
            statement.executeUpdate("""
                    INSERT INTO users (id, username, password, role)
                    VALUES (41, 'legacy-user', 'preserved-hash', 'PELANGGAN')
                    """);

            ScriptUtils.executeSqlScript(connection, new ClassPathResource("db/schema-v1.sql"));
            ScriptUtils.executeSqlScript(connection, new ClassPathResource("db/schema-v1.sql"));

            try (ResultSet result = statement.executeQuery(
                    "SELECT id, username, password, role, email FROM users WHERE id = 41")) {
                assertTrue(result.next());
                assertEquals(41L, result.getLong("id"));
                assertEquals("legacy-user", result.getString("username"));
                assertEquals("preserved-hash", result.getString("password"));
                assertEquals("PELANGGAN", result.getString("role"));
                assertNull(result.getString("email"));
            }
        }
    }

    @Test
    void fileBackedAuthDatabaseRetainsRowsWhenReopened(@TempDir Path tempDirectory) throws Exception {
        Path authDirectory = Files.createDirectories(tempDirectory.resolve("auth"));
        String databasePath = authDirectory.resolve("authdb").toString().replace('\\', '/');
        String jdbcUrl = "jdbc:h2:file:" + databasePath;

        try (Connection connection = DriverManager.getConnection(jdbcUrl, "sa", "")) {
            ScriptUtils.executeSqlScript(connection, new ClassPathResource("db/schema-v1.sql"));
            try (Statement statement = connection.createStatement()) {
                statement.executeUpdate("""
                        INSERT INTO users (username, password, role, email)
                        VALUES ('persistent-user', 'hash', 'PELANGGAN', 'user@example.test')
                        """);
            }
        }

        try (Connection reopened = DriverManager.getConnection(jdbcUrl, "sa", "");
             Statement statement = reopened.createStatement();
             ResultSet result = statement.executeQuery(
                     "SELECT username, email FROM users WHERE username = 'persistent-user'")) {
            assertTrue(result.next());
            assertEquals("persistent-user", result.getString("username"));
            assertEquals("user@example.test", result.getString("email"));
        }
    }
}
